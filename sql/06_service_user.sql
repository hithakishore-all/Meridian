-- 06_service_user.sql: the key-pair service user the Node app signs in as.
-- No password. The private key stays on your computer in the git-ignored .keys/ folder.
-- Before running: create the key pair (docs/SETUP_SNOWFLAKE.md, step 4) and paste the PUBLIC key body below
-- (the lines between BEGIN PUBLIC KEY and END PUBLIC KEY, joined into one line).

USE ROLE ACCOUNTADMIN;

CREATE USER IF NOT EXISTS MERIDIAN_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = MERIDIAN_APP
  DEFAULT_WAREHOUSE = MERIDIAN_WH
  COMMENT = 'Meridian Node app. Key-pair only.';

ALTER USER MERIDIAN_SVC SET RSA_PUBLIC_KEY = 'PASTE_PUBLIC_KEY_BODY_HERE';
GRANT ROLE MERIDIAN_APP TO USER MERIDIAN_SVC;

-- Least privilege: read the catalog and the governed view; write only what the app must record.
USE ROLE MERIDIAN_ADMIN;
GRANT USAGE ON DATABASE MERIDIAN TO ROLE MERIDIAN_APP;
GRANT USAGE ON SCHEMA MERIDIAN.CORE TO ROLE MERIDIAN_APP;
GRANT USAGE ON SCHEMA MERIDIAN.OPS TO ROLE MERIDIAN_APP;

GRANT SELECT ON ALL TABLES IN SCHEMA MERIDIAN.CORE TO ROLE MERIDIAN_APP;
GRANT SELECT ON ALL VIEWS IN SCHEMA MERIDIAN.CORE TO ROLE MERIDIAN_APP;
GRANT SELECT ON MERIDIAN.OPS.CONFIG TO ROLE MERIDIAN_APP;
GRANT SELECT ON MERIDIAN.OPS.V_USAGE TO ROLE MERIDIAN_APP;

-- What the app changes: buyer installs and policies, review decisions, and the operations log.
GRANT UPDATE ON MERIDIAN.CORE.INSTALLS TO ROLE MERIDIAN_APP;
GRANT UPDATE ON MERIDIAN.CORE.GROUP_POLICIES TO ROLE MERIDIAN_APP;
GRANT UPDATE ON MERIDIAN.CORE.TOOL_POLICIES TO ROLE MERIDIAN_APP;
GRANT UPDATE ON MERIDIAN.CORE.SUBMISSIONS TO ROLE MERIDIAN_APP;
GRANT SELECT, INSERT ON MERIDIAN.OPS.AUDIT TO ROLE MERIDIAN_APP;
GRANT SELECT, INSERT, UPDATE ON MERIDIAN.OPS.APPROVALS TO ROLE MERIDIAN_APP;
GRANT SELECT, INSERT ON MERIDIAN.OPS.CALLS TO ROLE MERIDIAN_APP;
GRANT SELECT, INSERT ON MERIDIAN.OPS.RUNS TO ROLE MERIDIAN_APP;
