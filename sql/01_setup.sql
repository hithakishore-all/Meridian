-- 01_setup.sql: warehouse, database, schemas and roles for Meridian.
-- Run as ACCOUNTADMIN (or a role that can create roles, warehouses and databases).
-- Safe to re-run.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS MERIDIAN_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Meridian demo: smallest size, suspends after 60 seconds';

CREATE DATABASE IF NOT EXISTS MERIDIAN COMMENT = 'Meridian agent marketplace demo. All data is fictional.';
CREATE SCHEMA IF NOT EXISTS MERIDIAN.CORE COMMENT = 'Catalog, workspaces, policies and agent evidence';
CREATE SCHEMA IF NOT EXISTS MERIDIAN.OPS  COMMENT = 'Config, audit log, approvals, metered calls';

-- Admin role: owns the objects. App role: least privilege for the Node app.
CREATE ROLE IF NOT EXISTS MERIDIAN_ADMIN;
CREATE ROLE IF NOT EXISTS MERIDIAN_APP;
GRANT ROLE MERIDIAN_ADMIN TO ROLE SYSADMIN;
GRANT ROLE MERIDIAN_APP TO ROLE MERIDIAN_ADMIN;

GRANT USAGE, OPERATE ON WAREHOUSE MERIDIAN_WH TO ROLE MERIDIAN_ADMIN;
GRANT USAGE ON WAREHOUSE MERIDIAN_WH TO ROLE MERIDIAN_APP;
GRANT OWNERSHIP ON DATABASE MERIDIAN TO ROLE MERIDIAN_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA MERIDIAN.CORE TO ROLE MERIDIAN_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA MERIDIAN.OPS TO ROLE MERIDIAN_ADMIN COPY CURRENT GRANTS;

-- Let you (the person running setup) use the admin role for the next scripts.
SET ME = CURRENT_USER();
GRANT ROLE MERIDIAN_ADMIN TO USER IDENTIFIER($ME);
