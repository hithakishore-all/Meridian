-- 02_tables.sql: tables for the catalog, workspaces, policies, evidence and operations.
-- Run as MERIDIAN_ADMIN after 01_setup.sql. CREATE OR REPLACE empties tables, so run 04_seed.sql after.

USE ROLE MERIDIAN_ADMIN;
USE WAREHOUSE MERIDIAN_WH;

-- ---------- catalog
CREATE OR REPLACE TABLE MERIDIAN.CORE.LISTINGS (
  LISTING_ID STRING PRIMARY KEY, NAME STRING, PUBLISHER STRING, CATEGORY STRING,
  FEATURED NUMBER(1), CONSUMER NUMBER(1), INSTALLS NUMBER, WEEKLY_ACTIVE_PCT NUMBER,
  EVAL_PCT NUMBER(5,1), P95_MS NUMBER, SOC2 STRING, DATA_REFRESHED_ON DATE,
  FRESHNESS_RULE_DAYS NUMBER, PRICE_MODEL STRING, DESCRIPTION STRING, KEYWORDS STRING
);
CREATE OR REPLACE TABLE MERIDIAN.CORE.TOOLS (
  LISTING_ID STRING, TOOL_NAME STRING, ACCESS STRING, DESCRIPTION STRING, CALLS_PER_RUN NUMBER
);
CREATE OR REPLACE TABLE MERIDIAN.CORE.PROMPTS (
  PROMPT_ID STRING PRIMARY KEY, LISTING_ID STRING, TOOL_NAME STRING, TEXT STRING
);
-- Every claim an agent can make, with its source, date and evidence ID.
-- KIND: fact | unknown | uncited (a draft claim the validator must reject) | action | link
CREATE OR REPLACE TABLE MERIDIAN.CORE.FACTS (
  EVIDENCE_ID STRING PRIMARY KEY, PROMPT_ID STRING, CLAIM STRING, SOURCE STRING,
  AS_OF DATE, KIND STRING, SOURCE_LISTING STRING
);

-- ---------- buyers
CREATE OR REPLACE TABLE MERIDIAN.CORE.WORKSPACES (
  WORKSPACE_ID STRING PRIMARY KEY, NAME STRING, KIND STRING, COMMITMENT_REMAINING_USD NUMBER(12,2)
);
CREATE OR REPLACE TABLE MERIDIAN.CORE.MEMBERS (
  USER_ID STRING, WORKSPACE_ID STRING, DISPLAY_NAME STRING, EMAIL STRING, GROUP_NAME STRING, IS_ADMIN NUMBER(1)
);
CREATE OR REPLACE TABLE MERIDIAN.CORE.INSTALLS (
  WORKSPACE_ID STRING, LISTING_ID STRING, STATUS STRING, PLAN STRING, PAY_VIA STRING,
  SPEND_CAP_USD NUMBER(12,2), HUMAN_WRITE NUMBER(1), PII_MASK NUMBER(1), POLICY_VERSION NUMBER,
  APPROVED_BY STRING, APPROVED_ON DATE
);
CREATE OR REPLACE TABLE MERIDIAN.CORE.GROUP_POLICIES (
  WORKSPACE_ID STRING, LISTING_ID STRING, GROUP_NAME STRING, ENABLED NUMBER(1)
);
CREATE OR REPLACE TABLE MERIDIAN.CORE.TOOL_POLICIES (
  WORKSPACE_ID STRING, LISTING_ID STRING, TOOL_NAME STRING, ENABLED NUMBER(1)
);

-- ---------- operator
CREATE OR REPLACE TABLE MERIDIAN.CORE.SUBMISSIONS (
  SUBMISSION_ID STRING PRIMARY KEY, PARTNER STRING, LISTING_NAME STRING, TYPE STRING, SUBMITTED_ON DATE,
  MANIFEST NUMBER(1), SCOPES NUMBER(1), PRIVACY NUMBER(1), EVALS NUMBER(1), LATENCY NUMBER(1), INJECTION NUMBER(1),
  EVAL_PCT NUMBER(5,1), P95_MS NUMBER, RISK STRING, NOTE STRING, STATUS STRING
);
CREATE OR REPLACE TABLE MERIDIAN.CORE.BOOKINGS_WEEKLY (WEEK_START DATE, BOOKINGS_USD NUMBER(14,2));
CREATE OR REPLACE TABLE MERIDIAN.CORE.FUNNEL (ORD NUMBER, STAGE STRING, COUNT NUMBER);
CREATE OR REPLACE TABLE MERIDIAN.CORE.ADOPTION (LISTING_ID STRING, INSTALLS NUMBER, WEEKLY_ACTIVE_PCT NUMBER, LIKELY_CAUSE STRING);
CREATE OR REPLACE TABLE MERIDIAN.CORE.SUPPLY_GAPS (QUERY STRING, WORKSPACES NUMBER);

-- ---------- operations
CREATE OR REPLACE TABLE MERIDIAN.OPS.CONFIG (CONFIG_KEY STRING PRIMARY KEY, CONFIG_VALUE STRING);
CREATE OR REPLACE TABLE MERIDIAN.OPS.AUDIT (
  EVENT_ID STRING, AT TIMESTAMP_NTZ, ACTOR STRING, WORKSPACE_ID STRING, LISTING_ID STRING,
  ACTION STRING, SURFACE STRING, POLICY_VERSION NUMBER, OUTCOME STRING, DETAIL STRING
);
CREATE OR REPLACE TABLE MERIDIAN.OPS.APPROVALS (
  APPROVAL_ID STRING PRIMARY KEY, IDEMPOTENCY_KEY STRING, WORKSPACE_ID STRING, LISTING_ID STRING,
  PROMPT_ID STRING, TOOL_NAME STRING, REQUESTED_BY STRING, SLACK_USER STRING, SURFACE STRING,
  STATUS STRING, REQUESTED_AT TIMESTAMP_NTZ, DECIDED_BY STRING, DECIDED_AT TIMESTAMP_NTZ
);
CREATE OR REPLACE TABLE MERIDIAN.OPS.CALLS (
  CALL_ID STRING, IDEMPOTENCY_KEY STRING, AT TIMESTAMP_NTZ, WORKSPACE_ID STRING, LISTING_ID STRING,
  TOOL_NAME STRING, CALLS NUMBER, COST_USD NUMBER(12,4)
);
-- Stored run results, so a retried request with the same idempotency key gets the same answer.
CREATE OR REPLACE TABLE MERIDIAN.OPS.RUNS (
  RUN_ID STRING PRIMARY KEY, IDEMPOTENCY_KEY STRING, AT TIMESTAMP_NTZ, RESULT VARIANT
);
