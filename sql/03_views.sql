-- 03_views.sql: the one governed view agents read, plus helper views.
-- Run as MERIDIAN_ADMIN after 02_tables.sql.

USE ROLE MERIDIAN_ADMIN;
USE WAREHOUSE MERIDIAN_WH;

-- The demo's "today" is pinned in OPS.CONFIG so freshness never drifts.
CREATE OR REPLACE VIEW MERIDIAN.CORE.V_DEMO_TODAY AS
SELECT TO_DATE(CONFIG_VALUE) AS DEMO_TODAY FROM MERIDIAN.OPS.CONFIG WHERE CONFIG_KEY = 'DEMO_TODAY';

-- Governed view: every claim with its source, date, evidence ID and a staleness flag.
-- A claim is stale when it comes from a data listing whose last refresh is older than that listing's rule.
CREATE OR REPLACE SECURE VIEW MERIDIAN.CORE.V_AGENT_FACTS AS
SELECT
  f.EVIDENCE_ID,
  f.PROMPT_ID,
  p.LISTING_ID,
  p.TOOL_NAME,
  f.CLAIM,
  NULLIF(f.SOURCE, '') AS SOURCE,
  f.AS_OF,
  f.KIND,
  NULLIF(f.SOURCE_LISTING, '') AS SOURCE_LISTING,
  src.DATA_REFRESHED_ON AS SOURCE_REFRESHED_ON,
  src.FRESHNESS_RULE_DAYS AS SOURCE_RULE_DAYS,
  IFF(src.FRESHNESS_RULE_DAYS IS NOT NULL
      AND DATEDIFF('day', src.DATA_REFRESHED_ON, t.DEMO_TODAY) > src.FRESHNESS_RULE_DAYS, TRUE, FALSE) AS IS_STALE,
  DATEDIFF('day', src.DATA_REFRESHED_ON, t.DEMO_TODAY) AS SOURCE_AGE_DAYS
FROM MERIDIAN.CORE.FACTS f
JOIN MERIDIAN.CORE.PROMPTS p ON p.PROMPT_ID = f.PROMPT_ID
LEFT JOIN MERIDIAN.CORE.LISTINGS src ON src.LISTING_ID = NULLIF(f.SOURCE_LISTING, '')
CROSS JOIN MERIDIAN.CORE.V_DEMO_TODAY t;

-- Listings with their own freshness state, for the catalog.
CREATE OR REPLACE VIEW MERIDIAN.CORE.V_LISTINGS AS
SELECT l.*,
  IFF(l.FRESHNESS_RULE_DAYS IS NOT NULL
      AND DATEDIFF('day', l.DATA_REFRESHED_ON, t.DEMO_TODAY) > l.FRESHNESS_RULE_DAYS, TRUE, FALSE) AS IS_STALE,
  DATEDIFF('day', l.DATA_REFRESHED_ON, t.DEMO_TODAY) AS DATA_AGE_DAYS
FROM MERIDIAN.CORE.LISTINGS l CROSS JOIN MERIDIAN.CORE.V_DEMO_TODAY t;

-- Usage per workspace and listing, from metered calls.
CREATE OR REPLACE VIEW MERIDIAN.OPS.V_USAGE AS
SELECT WORKSPACE_ID, LISTING_ID, SUM(CALLS) AS CALLS, SUM(COST_USD) AS COST_USD
FROM MERIDIAN.OPS.CALLS GROUP BY WORKSPACE_ID, LISTING_ID;
